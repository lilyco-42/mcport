#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""bridge26.py —— 组装「intermediary -> 26.x 去混淆真实名」专用改写表。

背景: 26.1 起 Mojang 完全去混淆, 官方 intermediary jar 变成 572B 空壳,
Fabric 不再提供 intermediary->official 映射。但 26.1 之前的官方 ProGuard
映射(proguard map) + Fabric intermediary 可以反推出每个 intermediary 名对应的
Mojang 真实名(bridge.py 已完成, 对齐率 ~99%)。把这些真实名按目标版本 26.x
的声明表校准, 就能把 1.21.1 时代编译的 mod 字节码改写到 26.1 命名空间。

输入:
  --bridge    两版基础桥 TSV(bridge.py 产), 可给多次, 靠后的优先级更高
  --src-decl  源版本 decl 表(提供 S 行 = intermediary 父类链)
  --dst-decl  目标版本 decl 表(提供 C 行 = 26.x 真实类名集合)
输出 (可直接作 RemapTool --map):
  C <interOwner> <realOwner>              # 类/描述符类型改写
  M <interOwner> <interDesc> <interName> <realName>
  F <interOwner> <interDesc> <interName> <realName>
  S <interOwner> <interSuper> <interIfaces,...>   # 继承解析用, intermediary 命名空间

三个校准动作(都是保守的, 命中不了就保留原值让 LinkCheck fail-loud):
  1) 版本择一: 同一 interOwner 在两版桥里指向不同真实名(如 1.21.1 的
     client/model/ElytraModel vs 1.21.11 的 client/model/object/equipment/ElytraModel),
     选目标 decl 里真实存在的那个。
  2) 目标感知重定位: 两版真实名都不在 26.1, 但 26.1 里存在唯一同名简单类
     (如 platform/GlStateManager 搬到 opengl/GlStateManager), 则重定向。
     简单名匹配到多个时不动, 避免误改。
  3) 父类链透传: RemapTool 收到的方法引用 owner 常常是子类/实现类, 而映射表
     的 key 是声明该成员的接口/父类。没有 S 行做继承解析, 491 条继承成员会漏改。
  4) allkeys/C/MF/S 全部 sorted() 输出: 输入来自集合, 不排序会字节序随机(见 main)。
"""
import argparse, collections, json

PRIM_OK = ('M', 'F')

def load_bridge(p):
    C, MF = {}, {}
    for ln in open(p, encoding='utf8'):
        q = ln.rstrip('\n').split('\t')
        if q[0] == 'C': C[q[1]] = q[2]
        elif q[0] in PRIM_OK: MF[(q[0], q[1], q[2], q[3])] = q[4]
    return C, MF

def load_super(p):
    S = {}
    for ln in open(p, encoding='utf8'):
        q = ln.rstrip('\n').split('\t')
        if q[0] == 'S': S[q[1]] = (q[2], q[3] if len(q) > 3 else '')
    return S

def load_classes(p):
    return set(q[1] for q in (ln.rstrip('\n').split('\t')
                             for ln in open(p, encoding='utf8')) if q[0] == 'C')

def simple(real):
    return real.rsplit('/', 1)[-1]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--bridge', action='append', required=True, help='可多次, 靠后优先')
    ap.add_argument('--src-decl', required=True)
    ap.add_argument('--dst-decl', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()

    bridges = [load_bridge(p) for p in a.bridge]
    D = load_classes(a.dst_decl)
    S = load_super(a.src_decl)
    bysimple = collections.defaultdict(list)
    for d in D: bysimple[simple(d)].append(d)

    allkeys = set()
    for C, _ in bridges: allkeys |= set(C)

    C, MF, stat = {}, {}, collections.Counter()
    for k in sorted(allkeys):
        # 靠后的桥优先, 与 --bridge 给定顺序一致
        cand = [c[k] for c, _ in reversed(bridges) if k in c]
        pick = next((x for x in cand if x in D), None)
        if pick: stat['exact'] += 1
        else:
            moved = None
            for x in cand:
                hits = bysimple.get(simple(x), [])
                if len(hits) == 1: moved = hits[0]; break
            if moved: pick = moved; stat['relocated'] += 1
            else: pick = cand[0]; stat['fallback'] += 1
        C[k] = pick
    for _, m in bridges: MF.update(m)

    with open(a.out, 'w', encoding='utf8') as f:
        f.write('# mcport bridge26: intermediary -> %s (generated by tools/bridge26.py)\n'
                % a.dst_decl.split('/')[-1])
        # 确定性输出: allkeys/C/MF/S 都来自 set/dict, 不排序则字节序随机。
        for k, v in sorted(C.items()): f.write('C\t%s\t%s\n' % (k, v))
        for (t, o, d, n), v in sorted(MF.items()): f.write('%s\t%s\t%s\t%s\t%s\n' % (t, o, d, n, v))
        for k, (s, ifs) in sorted(S.items()): f.write('S\t%s\t%s\t%s\n' % (k, s, ifs))
    stat.update(classes=len(C), members=len(MF), supers=len(S), target_classes=len(D))
    print(json.dumps(stat, ensure_ascii=False, sort_keys=True))

if __name__ == '__main__': main()
